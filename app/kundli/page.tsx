// app/kundli/page.tsx
"use client";

import { useState, useEffect, useRef } from "react";
import Link from "next/link";
import { ArrowLeft, Sparkles, Scroll, Download, RefreshCcw, AlertCircle, Star } from "lucide-react";
import { useApp } from "../Providers";

export default function KundliPage() {
  const { theme, lang, me } = useApp();
  const isDark = theme === "dark";

  const isHindi = lang === "hi";
  const isHinglish = lang === "hinglish";

  const t = (hi: string, hing: string, en: string) =>
    isHindi ? hi : isHinglish ? hing : en;

  const [name, setName] = useState("");
  const [dob, setDob] = useState("");
  const [time, setTime] = useState("");
  const [place, setPlace] = useState("");
  
  const [loading, setLoading] = useState(false);
  const [chart, setChart] = useState<any>(null);
  const [error, setError] = useState("");
  const [isDownloading, setIsDownloading] = useState(false);

  const pdfRef = useRef<HTMLDivElement>(null);

  // Auto-fill logic
  useEffect(() => {
    if (me?.birth) {
      setName(me.birth.name || "");
      setDob(me.birth.dob || "");
      setTime(me.birth.birthTime || "");
      setPlace(me.birth.birthPlace || "");
    }
  }, [me]);

  const pageClass = isDark ? "bg-[#0B1120] text-gray-200" : "bg-[#FEF8EF] text-slate-900";
  const cardClass = isDark ? "border-slate-700 bg-[#131C2E] shadow-lg" : "border-orange-100 bg-white shadow-sm";
  const inputClass = isDark
    ? "w-full rounded-xl border border-slate-700 bg-slate-900 p-3 text-sm focus:border-orange-500 focus:outline-none text-white"
    : "w-full rounded-xl border border-gray-300 bg-white p-3 text-sm focus:border-orange-500 focus:outline-none text-gray-900";

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setLoading(true);
    setError("");
    setChart(null);

    try {
      const res = await fetch("/api/kundli", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ 
          name, 
          dateOfBirth: dob, 
          timeOfBirth: time, 
          placeOfBirth: place 
        }),
      });
      const data = await res.json();
      
      if (!res.ok) throw new Error(data.error || t("कुंडली नहीं बन पाई।", "Kundli nahi ban payi.", "Failed to calculate Kundli."));
      
      setChart(data.chart);
    } catch (err: any) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleDownload = async () => {
    if (!pdfRef.current) return;
    setIsDownloading(true);
    
    try {
      // Wait for DOM to settle before capturing
      await new Promise((resolve) => setTimeout(resolve, 500));
      const html2pdf = (await import("html2pdf.js")).default;
      
      const opt = {
        margin:       10,
        filename:     `Kundli_${name || "User"}.pdf`,
        image:        { type: 'jpeg' as const, quality: 0.98 },
        html2canvas:  { scale: 2, useCORS: true, backgroundColor: "#ffffff" }, 
        jsPDF:        { unit: 'mm', format: 'a4', orientation: 'portrait' as const }
      };

      await html2pdf().set(opt).from(pdfRef.current).save();
    } catch (error) {
      console.error("PDF Generation Failed:", error);
      alert("PDF download failed. Please try again.");
    } finally {
      setIsDownloading(false);
    }
  };

  return (
    <main className={`min-h-screen w-full px-4 pb-20 pt-5 ${pageClass}`}>
      <div className="mx-auto max-w-md space-y-4">
        
        {/* HEADER */}
        <header className={`flex items-center gap-3 rounded-2xl border p-4 ${cardClass}`}>
          <Link href="/settings" className={`rounded-xl p-2 ${isDark ? "bg-slate-800 text-orange-400" : "bg-orange-50 text-orange-600"}`}>
            <ArrowLeft size={18} />
          </Link>
          <div>
            <h1 className="text-base font-black uppercase tracking-tight text-orange-500">
              {t("जन्म कुंडली", "Janam Kundli", "Janam Kundli")}
            </h1>
            <p className="text-xs text-slate-400">Generated by Gita AI</p>
          </div>
        </header>

        {/* FORM */}
        {!chart && (
          <form onSubmit={handleSubmit} className={`space-y-4 rounded-2xl border p-5 ${cardClass}`}>
            <div>
              <label className="text-sm font-bold opacity-80">{t("पूरा नाम", "Full Name", "Full Name")}</label>
              <input required value={name} onChange={e => setName(e.target.value)} className={inputClass} placeholder="e.g. Rahul Sharma" />
            </div>
            <div>
              <label className="text-sm font-bold opacity-80">{t("जन्म तिथि", "Date of Birth", "Date of Birth")}</label>
              <input required type="date" value={dob} onChange={e => setDob(e.target.value)} className={inputClass} />
            </div>
            <div>
              <label className="text-sm font-bold opacity-80">{t("जन्म का समय", "Time of Birth", "Time of Birth")}</label>
              <input required type="time" value={time} onChange={e => setTime(e.target.value)} className={inputClass} />
            </div>
            <div>
              <label className="text-sm font-bold opacity-80">{t("जन्म स्थान", "Place of Birth", "Place of Birth")}</label>
              <input required value={place} onChange={e => setPlace(e.target.value)} className={inputClass} placeholder="e.g. Patna, Bihar" />
            </div>

            {error && <p className="text-sm text-red-500 bg-red-500/10 p-3 rounded-lg font-medium">{error}</p>}

            <button type="submit" disabled={loading} className="w-full rounded-xl bg-orange-600 py-3 font-bold text-white transition-all hover:bg-orange-700 disabled:opacity-50 flex justify-center items-center gap-2">
              {loading ? (
                <><Sparkles className="animate-spin" size={18} /> {t("गणना हो रही है...", "Calculating...", "Calculating...")}</>
              ) : (
                t("कुंडली बनाएं", "Generate Kundli", "Generate Kundli")
              )}
            </button>
          </form>
        )}

        {/* RESULT (Professional Layout) */}
        {chart && (
          <div className="space-y-4">
            
            {/* 🔥 PDF CAPTURE AREA (White background for PDF quality) 🔥 */}
            <div 
              ref={pdfRef} 
              className="rounded-3xl border border-orange-500/30 bg-white p-5 text-slate-900 shadow-2xl relative overflow-hidden"
            >
              {/* Decorative Glow */}
              <div className="absolute -top-10 -right-10 w-32 h-32 bg-orange-500/10 blur-3xl rounded-full"></div>

              {/* Header Info */}
              <div className="flex justify-between items-start border-b border-gray-200 pb-4 mb-4">
                <div className="flex items-center gap-2">
                  <Scroll className="text-orange-600" size={24} />
                  <div>
                    <h2 className="text-xl font-bold text-slate-900">{t("जन्म कुंडली", "Birth Chart", "Birth Chart")}</h2>
                    <p className="text-[10px] text-gray-500 uppercase font-semibold tracking-wider">By Gita AI</p>
                  </div>
                </div>
                <div className="text-right">
                  <p className="font-bold text-sm text-slate-900">{name}</p>
                  <p className="text-[10px] text-gray-500">{dob} | {time}</p>
                  <p className="text-[10px] text-gray-500">{place}</p>
                </div>
              </div>
              
              {/* Core Details Grid */}
              <div className="grid grid-cols-2 gap-3 mb-5">
                <div className="bg-orange-50 p-3 rounded-xl border border-orange-100">
                  <p className="text-[10px] text-gray-500 font-semibold uppercase">{t("लग्न", "Lagna", "Lagna")}</p>
                  <p className="font-bold text-orange-700">{chart.lagna?.rashiNameHi || "N/A"}</p>
                </div>
                <div className="bg-orange-50 p-3 rounded-xl border border-orange-100">
                  <p className="text-[10px] text-gray-500 font-semibold uppercase">{t("राशि", "Rashi", "Moon Sign")}</p>
                  <p className="font-bold text-orange-700">{chart.moonSign?.rashiNameHi || "N/A"}</p>
                </div>
                <div className="bg-orange-50 p-3 rounded-xl border border-orange-100">
                  <p className="text-[10px] text-gray-500 font-semibold uppercase">{t("नक्षत्र", "Nakshatra", "Nakshatra")}</p>
                  <p className="font-bold text-orange-700">{chart.nakshatra?.name || "N/A"} <span className="text-xs font-normal">(Pada {chart.nakshatra?.pada || "-"})</span></p>
                </div>
                <div className="bg-orange-50 p-3 rounded-xl border border-orange-100">
                  <p className="text-[10px] text-gray-500 font-semibold uppercase">{t("वर्तमान दशा", "Current Dasha", "Current Dasha")}</p>
                  <p className="font-bold text-orange-700">{chart.currentDasha?.maha || "N/A"}</p>
                </div>
              </div>

              {/* Planets Table (Mockup Data if API doesn't provide yet) */}
              <div className="mb-5">
                <h3 className="text-sm font-bold text-slate-800 mb-2 flex items-center gap-1">
                  <Star size={14} className="text-orange-500" /> Graha Spashta (Planets)
                </h3>
                <div className="bg-gray-50 rounded-xl border border-gray-200 overflow-hidden text-xs">
                  <table className="w-full text-left">
                    <thead className="bg-gray-100 text-gray-500 uppercase">
                      <tr>
                        <th className="px-3 py-2">Planet</th>
                        <th className="px-3 py-2">Sign</th>
                        <th className="px-3 py-2 text-right">Degree</th>
                      </tr>
                    </thead>
                    <tbody className="divide-y divide-gray-200">
                      {/* Agar API se planets aate hain to chart.planets.map() use karein, warna dummy dikhayein */}
                      {(chart.planets || [
                        { name: "Sun (सूर्य)", sign: "वृषभ", degree: "21° 45'" },
                        { name: "Moon (चंद्र)", sign: "कुम्भ", degree: "12° 10'" },
                        { name: "Mars (मंगल)", sign: "मेष", degree: "05° 22'" },
                        { name: "Jupiter (गुरु)", sign: "वृश्चिक", degree: "28° 15'" },
                        { name: "Saturn (शनि)", sign: "सिंह", degree: "08° 05'" },
                      ]).map((planet: any, idx: number) => (
                        <tr key={idx} className="hover:bg-gray-100">
                          <td className="px-3 py-2 text-slate-800 font-medium">{planet.name}</td>
                          <td className="px-3 py-2 text-orange-600">{planet.sign}</td>
                          <td className="px-3 py-2 text-right text-gray-600">{planet.degree}</td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              </div>

              {/* Footer inside PDF */}
              <div className="text-center mt-6 pt-3 border-t border-gray-200">
                <p className="text-[10px] text-gray-400">Generated on {new Date().toLocaleDateString()} | www.gita-ai.com</p>
              </div>
            </div>
            {/* 🔥 PDF CAPTURE AREA END 🔥 */}

            {/* MARKETING HOOK (Bilkul Milan page jaisa) */}
            <div className="rounded-xl border border-red-500/30 bg-red-500/10 p-4">
              <p className="text-sm text-red-400 font-medium leading-relaxed">
                <span className="font-bold flex items-center gap-1 mb-1">
                  <AlertCircle size={14} /> {t("महत्वपूर्ण सूचना:", "Important Notice:", "Important Notice:")}
                </span> 
                {t(
                  "आपकी कुंडली में एक छिपा हुआ योग है जो विवाह या करियर में रुकावट डाल सकता है। सटीक कारण और उपाय जानने के लिए हमारे ज्योतिषी से बात करें।",
                  "Aapki kundli mein ek chhupa hua yog hai jo vivah ya career mein rukawat daal sakta hai. Exact cause aur upay jaanne ke liye humare astrologer se baat karein.",
                  "Your chart reveals a hidden dosha that may cause delays in marriage or career. Talk to our astrologer to know the exact cause and remedy."
                )}
              </p>
            </div>

            {/* RED CTA BUTTON */}
            <Link 
              href="/chat"
              className="w-full flex items-center justify-center gap-2 rounded-xl bg-gradient-to-r from-red-600 to-red-500 px-4 py-3.5 font-bold text-white shadow-lg shadow-red-500/20 transition-transform hover:scale-[1.02]"
            >
              <span className="text-xl">🔮</span> {t("ज्योतिषी से बात करें — पहली चैट मुफ्त", "Astrologer se baat karein — First chat FREE", "Talk to Astrologer — First chat FREE")}
            </Link>

            {/* ACTION BUTTONS */}
            <div className="flex gap-3">
              <button 
                onClick={handleDownload} 
                disabled={isDownloading}
                className="flex-1 rounded-xl bg-green-600 py-3 text-sm font-bold text-white hover:bg-green-700 disabled:opacity-50 flex items-center justify-center gap-2 transition-all"
              >
                {isDownloading ? (
                  <><Sparkles className="animate-spin" size={16} /> {t("रुकें...", "Wait...", "Wait...")}</>
                ) : (
                  <><Download size={16} /> {t("PDF डाउनलोड", "Download PDF", "Download PDF")}</>
                )}
              </button>
              
              <button 
                onClick={() => setChart(null)} 
                className="flex-1 rounded-xl border border-slate-700 py-3 text-sm font-bold text-slate-300 hover:bg-slate-800 flex items-center justify-center gap-2 transition-all"
              >
                <RefreshCcw size={16} /> {t("दोबारा बनाएं", "Calculate Again", "Calculate Again")}
              </button>
            </div>

          </div>
        )}

      </div>
    </main>
  );
}